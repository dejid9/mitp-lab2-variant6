"""Модуль для работы с числовыми рядами."""


def sum_odd_numbers(n: int) -> int:
    """Вычисляет сумму всех нечётных натуральных чисел, не превосходящих N.

    Параметры:
        n (int): Верхняя граница (включительно).

    Возвращает:
        int: Сумма нечётных чисел от 1 до N. При n < 1 возвращает 0.
    """
    if not isinstance(n, int):
        raise TypeError(f"Ожидалось целое число, получено: {type(n).__name__}")
    if n < 1:
        return 0
    return sum(i for i in range(1, n + 1, 2))
